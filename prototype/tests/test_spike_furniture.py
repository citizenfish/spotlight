def test_the_surge_plan_draws_solid_furniture_as_wall():
    """The plan says where you cannot walk, and a crate is somewhere you
    cannot walk. Counted through `surge.draw`'s own drawing: a room whose
    only interior solid cell is a crate lights one more plan cell than the
    same room with floor there, and a grating lights none."""
    def solid_plan_cells(room):
        screen = Screen()
        surge.draw(screen, [room], [])
        return sum(1 for p in screen.pixels if p)

    empty = _blank_room()
    crate = _blank_room(at={(10, 10): building.CRATE})
    wall = _blank_room(at={(10, 10): building.WALL})
    grating = _blank_room(at={(10, 10): building.GRATING})
    assert solid_plan_cells(crate) == solid_plan_cells(wall) \
        > solid_plan_cells(empty) == solid_plan_cells(grating)


