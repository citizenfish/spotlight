"""Furniture: seven tiles a room can be authored with (issue #74).

From *A place, not a diagram* in the vault. **What was wrong before**: the
building was a diagram. Rule 5 of *Art Direction* -- anything drawn is a claim
that it matters -- had been read as *nothing is drawn that is not a mechanic*,
so a building where seven people are bleeding to death had no desk in it. The
fix is seven tiles with a legend character each: six that are walls for every
mechanical purpose and draw their own tile instead of the masonry, and one
that is floor and draws its own tile instead of the stipple. The dim variant
of each is generated by rule, never drawn.

The tests here pin four things separately, because they can fail separately:

* **the legend** -- a solid kind is solid and is wall to its neighbours' masks
  everywhere the game asks, the grating is not, and the surge's plan agrees;
* **the art** -- the seven lit tiles came through the pipeline, the dim tiles
  are the rule applied to them and nothing else, and none of them is an
  octagon, because the lamp family's silhouette is reserved;
* **the drawing** -- a solid piece draws its own tile instead of the wall's
  and never the masonry under it, a grating draws instead of the stipple, a
  dark cell draws nothing, and paint hides texture here as it does on walls;
* **the geometry** -- each room's solidity bitmap is held against a stored
  copy, so that a piece of furniture authored onto floor, which would move
  collision, the swarm's reach and the event log, has to change this file on
  purpose. That last pin is what makes the slice log-identical by
  construction rather than by luck.
"""

