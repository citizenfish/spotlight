@pytest.mark.parametrize("kind", building.FURNITURE)
def test_each_dim_tile_is_the_rule_applied_to_its_lit_tile(kind):
    """Row `y` of the lit tile ANDed with 0xAA when `y` is even and 0x55 when
    odd -- every other pixel, phase alternating by row. Written out here
    rather than through `tiles.dim_of`, so that the rule is pinned and not
    merely whatever the function does; and then through it, so the table is
    the function's output and not a hand-drawn second set."""
    lit = tiles.FURNITURE[kind]
    want = tuple(bits & (0xAA if y % 2 == 0 else 0x55)
                 for y, bits in enumerate(lit))
    assert tiles.FURNITURE_DIM[kind] == want
    assert tiles.dim_of(lit) == want
    # A ghost and not a second drawing: nothing set that the lit tile has not.
    assert all(d & ~l == 0 for d, l in zip(want, lit))
    # A checker, not stripes: every dim row keeps only pixels of one parity,
    # and adjacent rows keep opposite parities.
    for y, bits in enumerate(want):
        keep = 0xAA if y % 2 == 0 else 0x55
        assert bits & ~keep == 0


def test_the_dim_tiles_are_not_in_the_generated_table():
    """Generated at load and not by the converter, so the port's ROM figure
    is the 56 lit bytes: the asset holds seven blocks and the table holds no
    `*_DIM` for any of them."""
    for name in KINDS.values():
        assert f"{name}_DIM" not in BITMAPS
    furniture_blocks = [n for n in BITMAPS if n in KINDS.values()]
    assert len(furniture_blocks) == 7


def test_the_dim_rule_loses_about_half_of_every_solid_tile():
    """The point of the rule is a ghost, and a ghost is thinner. Nothing has
    to be exactly half -- an outline row of 0xFF loses four of eight, a row of
    0x81 may keep both or neither -- but no solid tile keeps more than it
    loses. The grating keeps six of nine, and has its own test below, because
    a grille of dots is already sparse and a third of it is all the rule can
    take without taking the lot."""
    for kind in building.SOLID_FURNITURE:
        lit = tiles.ink_of(tiles.FURNITURE[kind])
        dim = tiles.ink_of(tiles.FURNITURE_DIM[kind])
        assert 0 < dim <= lit // 2 + 1, (kind, lit, dim)


def test_the_grating_thins_when_remembered_like_everything_else():
    """**The exception that became the ordinary case** (issue #77). As #74
    drew it the grating was three rows of `.#.#.#..` on rows 1, 3 and 5 --
    every dot on an odd pixel of an odd row, the half the rule keeps -- so
    `dim_of(GRATING) == GRATING` and a remembered grating showed nine dots
    beside floor that remembers one: the one tile that handed over more when
    remembered than when seen, the opposite of what the fade says. The
    ruling was that the art gives, not the rule: row 3 is `..#.#.#.` now,
    and the rule drops it.

    So the grating is pinned exactly as the other six are -- the dim tile is
    the rule applied to the lit one and a strict subset of it -- and with
    the numbers the ruling named: nine lit, six remembered. The last two
    assertions pin the thing that was wrong, on the two drawings that were
    considered and refused: a grille all on one pixel parity survives the
    rule whole (the #74 tile) or not at all (the same dots on even pixels),
    which is why a shift of one row and not of all three.
    """
    lit = tiles.FURNITURE[building.GRATING]
    dim = tiles.FURNITURE_DIM[building.GRATING]
    assert tiles.ink_of(lit) == 9
    assert tiles.ink_of(dim) == 6
    assert dim == tiles.dim_of(lit)
    assert dim != lit
    assert all(d & ~l == 0 for d, l in zip(dim, lit)), "dim is a subset of lit"
    # Rows 1 and 5 survive whole; row 3, the staggered one, goes.
    assert [y for y, bits in enumerate(lit) if bits] == [1, 3, 5]
    assert [y for y, bits in enumerate(dim) if bits] == [1, 5]
    assert lit[3] == 0x2A and dim[3] == 0x00
    assert dim[1] == lit[1] and dim[5] == lit[5]
    # The two refused drawings, so the reason for the stagger stays checkable.
    as_first_drawn = (0x00, 0x54, 0x00, 0x54, 0x00, 0x54, 0x00, 0x00)
    assert tiles.dim_of(as_first_drawn) == as_first_drawn
    all_even_pixels = (0x00, 0xA8, 0x00, 0xA8, 0x00, 0xA8, 0x00, 0x00)
    assert tiles.ink_of(tiles.dim_of(all_even_pixels)) == 0


#: The lamp's outline: an octagon, and the lamp family's alone. LAMP_OFF is
#: the hollow one, LAMP_ON fills it, and the housing is the same shape.
LAMP_OUTLINE = BITMAPS["LAMP_OFF"]


def test_no_furniture_tile_has_the_lamps_outline_rows():
    """A spotlight lying on the floor is the one object a player has to pick
    out of a room at a glance, so nothing else in a room may be round. The
    vault drew a drum and threw it away for this reason. Pinned as *no tile
    has the lamp's outline rows*: not its top-and-bottom chamfer pair, and
    not its rows at all."""
    chamfer = (LAMP_OUTLINE[0], LAMP_OUTLINE[7])
    assert chamfer == (0x3C, 0x3C), "the lamp is no longer an octagon?"
    for kind in building.FURNITURE:
        for table in (tiles.FURNITURE, tiles.FURNITURE_DIM):
            rows = table[kind]
            assert rows != LAMP_OUTLINE
            assert (rows[0], rows[7]) != chamfer, \
                f"{KINDS[kind]} is chamfered top and bottom like a lamp"
            # Nor the octagon's middle: the four 0x81 rows between the
            # chamfers, which is what makes a hollow octagon read as one.
            assert rows[1:7] != LAMP_OUTLINE[1:7], KINDS[kind]


def test_the_asset_says_why_the_dim_tiles_are_not_in_it():
    """The file is the source, so the rule that governs what is *not* in it
    has to be written there, where the next author will look."""
    text = ASSET.read_text()
    assert "dim" in text.lower() and "rule" in text.lower()
    assert "$AA" in text and "$55" in text


