def test_the_legend_has_seven_furniture_characters_and_no_two_alike():
    """The count is the rule; the glyphs are a choice. Seven kinds, six of
    them solid, none of them a character the legend already had."""
    assert len(building.FURNITURE) == 7
    assert len(set(building.FURNITURE)) == 7
    assert building.SOLID_FURNITURE == building.FURNITURE[:6]
    assert building.GRATING == building.FURNITURE[6]
    old = {building.WALL, building.FLOOR, building.DOOR, building.KEY,
           building.DOORWAY}
    assert not old & set(building.FURNITURE)
    assert set(building.CELL_KINDS) == old | set(building.FURNITURE)


@pytest.mark.parametrize("kind", building.SOLID_FURNITURE)
def test_each_solid_kind_is_solid_and_is_wall_everywhere_it_is_asked(kind):
    """`is_solid` is the authority on what is walkable and `is_wall` on what
    the tile mask sees, and a solid piece answers as `#` to both. There is
    no third list to keep in step: both read `building.SOLID`."""
    assert kind in building.SOLID
    room = _blank_room(at={(10, 10): kind})
    assert room.is_solid(10, 10)
    assert room.is_wall(10, 10)
    assert room.furniture_at(10, 10) == kind


@pytest.mark.parametrize("kind", building.SOLID_FURNITURE)
def test_a_solid_piece_is_wall_to_its_neighbours_masks(kind):
    """The cell east of a crate has WEST set, and so on round it -- which is
    what makes a wall run end against a pipe the way it ends against
    masonry, and what the floor pass needs so it does not stipple a desk."""
    room = _blank_room(at={(10, 10): kind})
    assert tiles.mask_at(room.is_wall, 11, 10) & tiles.WEST
    assert tiles.mask_at(room.is_wall, 9, 10) & tiles.EAST
    assert tiles.mask_at(room.is_wall, 10, 11) & tiles.NORTH
    assert tiles.mask_at(room.is_wall, 10, 9) & tiles.SOUTH
    # And the piece itself, boxed in by walls, would see all four -- not that
    # its own tile is chosen by a mask, see the drawing tests.
    boxed = _blank_room(at={(10, 10): kind, (9, 10): "#", (11, 10): "#",
                            (10, 9): "#", (10, 11): "#"})
    assert tiles.mask_at(boxed.is_wall, 10, 10) == 15


def test_the_grating_is_floor_everywhere_it_is_asked():
    """Walkable, not wall to a neighbour's mask, and floor to the swarm: a
    grille in the floor is somewhere a fly can stand."""
    from spikes import swarming
    assert building.GRATING not in building.SOLID
    room = _blank_room(at={(10, 10): building.GRATING})
    assert not room.is_solid(10, 10)
    assert not room.is_wall(10, 10)
    assert room.furniture_at(10, 10) == building.GRATING
    assert tiles.mask_at(room.is_wall, 11, 10) == 0
    # The swarm starts from where the flies are, never from a grid over the
    # floor, so the scratch room needs a fly in it to have anywhere reached.
    swarmed = building.Room("scratch", room.rows, clegs=[(5, 5)])
    assert (10, 10) not in swarming.unswarmable(swarmed)


