def _solidity(room) -> tuple:
    """A room's solidity bitmap as the stored copy is written."""
    bits = room.solid_map()
    return tuple("".join("#" if bits[cy * COLS + cx] else "."
                         for cx in range(COLS))
                 for cy in range(PLAY_ROWS))


def _blank_room(**cells) -> building.Room:
    """A scratch room: a `#` border, floor inside, and `cells` placed in it,
    given as `{(cx, cy): char}` via the single keyword `at`."""
    at = cells.get("at", {})
    rows = []
    for cy in range(PLAY_ROWS):
        row = []
        for cx in range(COLS):
            edge = cx in (0, COLS - 1) or cy in (0, PLAY_ROWS - 1)
            row.append(at.get((cx, cy), "#" if edge else "."))
        rows.append("".join(row))
    return building.Room("scratch", rows)


def _field(*cells) -> L.LightField:
    """A light field with the given `(cx, cy, level)` cells set."""
    f = L.LightField()
    f.begin()
    for cx, cy, level in cells:
        f.add(cx, cy, level, L.CHARGE_LIT if level == L.LIT else L.CHARGE_DIM)
    f.commit()
    return f


def _cell(screen, cx, cy) -> tuple:
    """A cell's eight rows, as the bytes a tile would have set."""
    out = []
    for dy in range(CELL):
        bits = 0
        for dx in range(CELL):
            if screen.pixels[(cy * CELL + dy) * SCREEN_W + cx * CELL + dx]:
                bits |= 0x80 >> dx
        out.append(bits)
    return tuple(out)


