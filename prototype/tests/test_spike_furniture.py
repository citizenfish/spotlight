def test_the_wall_beside_a_piece_of_furniture_ends_against_it():
    """The neighbours' masks are the whole reason a solid piece is in
    `SOLID` and not merely drawn: the wall cell west of a pipe run sees a
    wall to its east, so it draws no east face and the run reads as one
    thing. Compared against the same cell beside floor."""
    with_pipe = _blank_room(at={(1, 10): building.PIPE_H})
    without = _blank_room()
    field = _field((0, 10, L.LIT))
    a, b = Screen(), Screen()
    tiles.draw(a, with_pipe, field)
    tiles.draw(b, without, field)
    assert tiles.mask_at(with_pipe.is_wall, 0, 10) & tiles.EAST
    assert not tiles.mask_at(without.is_wall, 0, 10) & tiles.EAST
    assert _cell(a, 0, 10) == tiles.WALL_LIT[tiles.mask_at(with_pipe.is_wall, 0, 10)]
    assert _cell(a, 0, 10) != _cell(b, 0, 10)


