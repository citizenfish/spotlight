BLANK = GLYPHS[" "]

MISSING = (0x00, 0x7C, 0x7C, 0x7C, 0x7C, 0x7C, 0x7C, 0x00)


def draw_glyph(screen: Screen, cx: int, cy: int, rows: tuple[int, ...]) -> None:
    """Draw one 8x8 glyph into the cell at (cx, cy). Pixels only, no attributes."""
    x0, y0 = cx * CELL, cy * CELL
    for dy, bits in enumerate(rows):
        base = (y0 + dy) * SCREEN_W + x0
        for dx in range(CELL):
            screen.pixels[base + dx] = 1 if bits & (0x80 >> dx) else 0


def draw_text(screen: Screen, cx: int, cy: int, text: str) -> int:
    """Draw text from cell (cx, cy). Returns the column after the last glyph."""
    for i, ch in enumerate(text.upper()):
        draw_glyph(screen, cx + i, cy, GLYPHS.get(ch, MISSING))
    return cx + len(text)
